"""Embeds the TMX site logos (assets/sites/<host>.png, see assets/sites/SOURCES.md) into
src/plugin/site_logos.inc as byte arrays. Run after changing a logo: python assets/make_site_logos.py"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SITES = ["tmnf.exchange", "tmuf.exchange", "nations.tm-exchange.com", "sunrise.tm-exchange.com", "original.tm-exchange.com"]

out = ["// Generated by assets/make_site_logos.py from assets/sites/*.png (logos: see assets/sites/SOURCES.md).", ""]
names = []
for i, host in enumerate(SITES):
    data = open(os.path.join(HERE, "sites", host + ".png"), "rb").read()
    name = "kLogo%d" % i
    names.append((host, name, len(data)))
    out.append("static const unsigned char %s[%d] = {" % (name, len(data)))
    for k in range(0, len(data), 24):
        out.append("    " + ",".join(str(b) for b in data[k:k + 24]) + ",")
    out.append("};")
out.append("")
out.append("struct SiteLogoData { const char* host; const unsigned char* png; unsigned size; };")
out.append("static const SiteLogoData kSiteLogos[] = {")
for host, name, size in names:
    out.append('    {"%s", %s, %d},' % (host, name, size))
out.append("};")
open(os.path.join(HERE, "..", "src", "plugin", "site_logos.inc"), "w", newline="\n").write("\n".join(out) + "\n")
print("wrote site_logos.inc")
